/*
 * The burning RML logo, JavaScript version of drafts/flammen/sim/firesim7.py.
 *
 * The letters R, M, L are made of fire: their shape is a burning zone in a heat field, hottest in
 * the core of each stroke. Every spot breathes in its own rhythm, so the heat leaves the letters in
 * waves and rises as flames. Edges burn away as notches where it is quiet and grow back when a
 * wave hits; burnt pixels stay visible, only darker. Smoke, sparks and embers that crackle, and a
 * small fire in the lantern that never burns away.
 *
 * The fixed shapes come from rml-fire-data.js (window.RML_FIRE_DATA), generated by export_data.py.
 *
 * Usage:  const fire = RMLFire.start(canvas);   // canvas gets W x H pixels, scale it with CSS
 *         fire.stop();
 * With "reduce motion" switched on in macOS the logo is drawn once and stands still.
 */
(function () {
  "use strict";

  // --- tuning (same values as firesim7.py) -------------------------------------------------
  const STEP_MS = 80;
  const FLAME_COOL = 0.03, FLAME_JITTER = 0.05;
  const HIT = 0.8;              // a heat wave above this hits the edge and lets a notch grow back
  const QUIET = 0.42;           // below this the edge is quiet and may burn
  const NOTCH_START = 0.4;      // chance per step that a new notch starts somewhere quiet
  const NOTCH_SPREAD = 0.3;     // chance per step that a quiet notch grows one pixel longer at an end
  const NOTCH_DEEPEN = 0.1;     // how fast a quiet notch gets deeper
  const NOTCH_HEAL = 0.1;       // how fast a notch grows back when a wave hits it
  const NOTCH_REGROW = 0.0;     // slow regrowth on its own where it is not quiet
  const CHAR_GLOW = 0.4;        // burnt-away pixels still glow this much of their normal heat
  const CHAR_GLOW_OUTER = 0.2;  // ... and the outer one of a notch 2 deep only this much
  const BURNT_DARKEN = 0.4;     // burnt-away pixels stay visible, this much darker
  const BURNT_DARKEN_OUTER = 0.5;
  const MIN_GLOW = 0.22;        // letter pixels never get colder than this, so the shape stays visible

  const SILVER = [0xcf, 0xc9, 0xbd];
  const FIRE_RAMP = [
    [0x3a, 0x0f, 0x1c], [0x5e, 0x15, 0x28], [0x7e, 0x1e, 0x36], [0xa5, 0x2a, 0x46],
    [0xc9, 0x41, 0x5c], [0xe0, 0x7a, 0x8c], [0xf4, 0xb7, 0xbf],
  ];
  const SMOKE = [[0x57, 0x5b, 0x64], [0x3b, 0x3f, 0x48], [0x2a, 0x2d, 0x35]]; // dense to thin

  // --- noise, bit for bit the same as in Python -----------------------------------------------
  function h3(x, y, z) {
    let n = (Math.imul(x, 374761393) + Math.imul(y, 668265263) + Math.imul(z, 2147483647)) >>> 0;
    n = Math.imul(n ^ (n >>> 13), 1274126177) >>> 0;
    return ((n ^ (n >>> 16)) & 0xffffff) / 0xffffff;
  }
  function vnoise(x, y, z) {
    const xi = Math.floor(x), yi = Math.floor(y), zi = Math.floor(z);
    let fx = x - xi, fy = y - yi, fz = z - zi;
    fx = fx * fx * (3 - 2 * fx); fy = fy * fy * (3 - 2 * fy); fz = fz * fz * (3 - 2 * fz);
    const l = (a, b, t) => a + (b - a) * t;
    return l(l(l(h3(xi, yi, zi), h3(xi + 1, yi, zi), fx), l(h3(xi, yi + 1, zi), h3(xi + 1, yi + 1, zi), fx), fy),
             l(l(h3(xi, yi, zi + 1), h3(xi + 1, yi, zi + 1), fx), l(h3(xi, yi + 1, zi + 1), h3(xi + 1, yi + 1, zi + 1), fx), fy), fz);
  }
  function mulberry32(seed) {
    return function () {
      seed = (seed + 0x6d2b79f5) | 0;
      let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  const ramp = (v, colours) => colours[Math.max(0, Math.min(colours.length - 1, Math.floor(v * colours.length)))];

  function create(data, seed) {
    const { W, H, base } = data;
    const rnd = mulberry32(seed);
    const uniform = (a, b) => a + (b - a) * rnd();
    const randint = (a, b) => a + Math.floor(rnd() * (b - a + 1));
    const at = (x, y) => y * W + x;

    const isBody = new Uint8Array(W * H);
    for (const [x, y] of data.body) isBody[at(x, y)] = 1;

    const fuel = data.fuel.map(([x, y, depth, origin]) => ({
      x, y, depth, origin,
      core: Math.min(1, (depth - 1) / Math.max(1, data.maxDepth - 1)),
      phase: vnoise(x * 0.09, y * 0.09, 3.3) * 4 * Math.PI,
      speed: 0.12 + 0.12 * vnoise(x * 0.05, y * 0.05, 8.1),
      pulse: 0, crackle: 0, unburnt: MIN_GLOW, gone: false,
    }));
    // the outline point index of every letter pixel that lies on the edge
    const fuelAtOutline = new Int32Array(data.outline.length).fill(-1);
    fuel.forEach((f, i) => { if (f.depth === 1) fuelAtOutline[f.origin] = i; });
    const outline = data.outline.map(([x, y, allow, along]) => ({ x, y, allow, along, burn: 0 }));
    const lantern = data.lanternZone.map(([x, y, depth]) => ({
      x, y,
      core: Math.min(1, (depth - 1) / Math.max(1, data.lanternMaxDepth - 1)),
      phase: vnoise(x * 0.3, y * 0.3, 6.6) * 4 * Math.PI,
      speed: 0.14 + 0.1 * vnoise(x * 0.2, y * 0.2, 2.9),
    }));

    let heat = new Float32Array(W * H), next = new Float32Array(W * H);
    let smoke = new Float32Array(W * H), snext = new Float32Array(W * H);
    const sparks = [];

    function step(t) {
      const wind = Math.sin(t * 0.13) * 0.6 + Math.sin(t * 0.051 + 1.7) * 0.4;
      next.fill(0);
      for (let y = 0; y < H - 1; y++) {
        for (let x = 0; x < W; x++) {
          if (isBody[at(x, y)]) continue;
          // turbulence: a smooth noise field that rises with the flames decides the sideways pull
          const n = vnoise(x * 0.16, (y + t * 1.2) * 0.16, t * 0.02) + wind * 0.12;
          const dx = n < 0.36 ? -1 : n > 0.64 ? 1 : 0;
          const sx = Math.min(W - 1, Math.max(0, x + dx));
          if (isBody[at(sx, y + 1)]) continue;
          const l = heat[at(Math.max(0, sx - 1), y + 1)], r = heat[at(Math.min(W - 1, sx + 1), y + 1)];
          let v = 0.7 * heat[at(sx, y + 1)] + 0.15 * (l + r);
          // cooler gaps that drift up split the fire into separate tongues
          const gap = vnoise(x * 0.22, (y + t * 1.2) * 0.22, 5.0);
          v -= FLAME_COOL + gap * 0.05 + rnd() * FLAME_JITTER;
          if (v > 0) next[at(x, y)] = v;
        }
      }
      // the letters feed heat into the field, most in the core, each spot in its own rhythm
      for (const f of fuel) {
        f.pulse = 0.5 + 0.5 * Math.sin(t * f.speed + f.phase);
        const src = (0.55 + 0.55 * f.core) * (0.55 + 0.45 * f.pulse) * uniform(0.85, 1.05);
        const i = at(f.x, f.y);
        f.unburnt = Math.max(next[i], src, MIN_GLOW);
        if (f.gone) {
          const outer = f.depth < Math.floor(outline[f.origin].burn);
          next[i] = Math.max(next[i] * 0.4, src * (outer ? CHAR_GLOW_OUTER : CHAR_GLOW));
          continue;
        }
        next[i] = Math.max(next[i], src, MIN_GLOW);
      }
      // the lantern flame burns the same way, but it never burns away
      for (const p of lantern) {
        const pulse = 0.5 + 0.5 * Math.sin(t * p.speed + p.phase);
        const src = (0.55 + 0.55 * p.core) * (0.55 + 0.45 * pulse) * uniform(0.85, 1.05);
        const i = at(p.x, p.y);
        next[i] = Math.max(next[i], src, MIN_GLOW);
      }
      [heat, next] = [next, heat];

      // notches along the edge
      for (let k = 0; k < outline.length; k++) {
        const o = outline[k], pulse = fuel[fuelAtOutline[k]].pulse;
        if (pulse > HIT) o.burn = Math.max(0, o.burn - NOTCH_HEAL);
        else if (pulse >= QUIET) o.burn = Math.max(0, o.burn - NOTCH_REGROW);
        else if (o.burn >= 1) o.burn += NOTCH_DEEPEN;
        else if (o.along.some(n => outline[n].burn >= 1) && rnd() < NOTCH_SPREAD) o.burn = 1;
      }
      if (rnd() < NOTCH_START) {
        const k = Math.floor(rnd() * outline.length), o = outline[k];
        if (fuel[fuelAtOutline[k]].pulse < QUIET && o.burn === 0 && o.allow >= 1) {
          for (const n of [k, ...o.along.slice(0, 2)]) {
            if (outline[n].allow >= 1) outline[n].burn = Math.max(outline[n].burn, 1);
          }
        }
      }
      // never deeper than the stroke allows, and the ends of a notch stay stepped
      for (const o of outline) {
        let cap = o.allow ? o.allow + 0.999 : 0;
        if (o.along.length) cap = Math.min(cap, Math.min(...o.along.map(n => outline[n].burn)) + 1);
        o.burn = Math.min(o.burn, cap);
      }
      for (const f of fuel) f.gone = f.y !== base && f.depth <= Math.floor(outline[f.origin].burn);

      // embers crackle
      for (const f of fuel) {
        f.crackle *= 0.55;
        if (rnd() < 0.006) f.crackle = uniform(0.3, 0.5);
      }

      // smoke: the cooling tips of the flames feed it; it rises slowly, drifts and thins out
      snext.fill(0);
      for (let y = 0; y < H - 1; y++) {
        for (let x = 0; x < W; x++) {
          let v;
          if (rnd() < 0.6) {
            const r = rnd();
            const sx = Math.min(W - 1, Math.max(0, x + (r < 0.25 - wind * 0.2 ? -1 : r > 0.75 - wind * 0.2 ? 1 : 0)));
            v = smoke[at(sx, y + 1)];
          } else {
            v = smoke[at(x, y)];
          }
          v *= 0.94;
          const hv = heat[at(x, y)];
          if (hv > 0.04 && hv < 0.3) v += 0.07 * rnd();
          snext[at(x, y)] = Math.min(1, v);
        }
      }
      [smoke, snext] = [snext, smoke];

      // sparks fly up now and then
      if (rnd() < 0.18) {
        const [x, y] = data.sparkSources[Math.floor(rnd() * data.sparkSources.length)];
        sparks.push({ x, y, age: 0, life: randint(6, 11) });
      }
      for (const s of sparks) {
        s.age += 1; s.y -= 1;
        if (rnd() < 0.4) s.x += rnd() < 0.5 ? -1 : 1;
      }
      for (let i = sparks.length - 1; i >= 0; i--) {
        if (sparks[i].age >= sparks[i].life || sparks[i].y < 0) sparks.splice(i, 1);
      }
    }

    function draw(img) {
      const d = img.data;
      const put = (x, y, c) => { const i = (y * W + x) * 4; d[i] = c[0]; d[i + 1] = c[1]; d[i + 2] = c[2]; d[i + 3] = 255; };
      for (let y = 0; y < H; y++) {
        for (let x = 0; x < W; x++) {
          const s = smoke[at(x, y)], v = heat[at(x, y)];
          let c = null;
          if (s > 0.18) c = s < 0.3 ? SMOKE[2] : s < 0.5 ? SMOKE[1] : SMOKE[0];
          if (v > 0.1) c = ramp(Math.min(0.999, (v - 0.1) / 0.8), FIRE_RAMP);
          if (c) put(x, y, c);
          else d[(y * W + x) * 4 + 3] = 0;   // empty air stays see-through, so the page shows behind it
        }
      }
      for (const f of fuel) {
        if (f.gone) {
          // burnt away, but still there: the colour it would have, only darker
          const outer = f.depth < Math.floor(outline[f.origin].burn);
          const keep = 1 - (outer ? BURNT_DARKEN_OUTER : BURNT_DARKEN);
          const c = ramp(Math.min(0.999, Math.max(0, f.unburnt - 0.1) / 0.8), FIRE_RAMP);
          put(f.x, f.y, [Math.round(c[0] * keep), Math.round(c[1] * keep), Math.round(c[2] * keep)]);
        } else if (f.crackle > 0.15) {
          put(f.x, f.y, FIRE_RAMP[6]);           // a hot spark in the core now and then
        }
      }
      for (const [x, y] of data.body) put(x, y, SILVER);
      for (const s of sparks) {
        if (s.x >= 0 && s.x < W) put(s.x, s.y, FIRE_RAMP[Math.max(2, 6 - Math.floor(s.age * 5 / s.life))]);
      }
    }

    return { W, H, step, draw };
  }

  function start(canvas, options = {}) {
    const data = options.data || window.RML_FIRE_DATA;
    const sim = create(data, options.seed || 11);
    canvas.width = sim.W;
    canvas.height = sim.H;
    const ctx = canvas.getContext("2d");
    const img = ctx.createImageData(sim.W, sim.H);
    let t = 0;
    for (; t < 40; t++) sim.step(t);                // warm up, so it is burning from the first frame
    const render = () => { sim.draw(img); ctx.putImageData(img, 0, 0); };
    render();

    const still = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (still) return { stop() {} };
    let last = performance.now(), frame = 0, running = true;
    function tick(now) {
      if (!running) return;
      if (now - last >= STEP_MS) {
        // never catch up more than a few steps, e.g. after the window was hidden
        const steps = Math.min(3, Math.floor((now - last) / STEP_MS));
        for (let i = 0; i < steps; i++) sim.step(t++);
        last = now;
        render();
      }
      frame = requestAnimationFrame(tick);
    }
    frame = requestAnimationFrame(tick);
    return { stop() { running = false; cancelAnimationFrame(frame); } };
  }

  window.RMLFire = { start, create };
})();
